using System.ComponentModel;

namespace Notes.Core.Sync;

/// <summary>
/// Documentation of the common fields every entity's <c>data</c> contains. Not used at runtime (data is handled as JSON
/// to preserve unknown fields) – only to describe the contract in <c>api/openapi.json</c>.
/// </summary>
public abstract record SyncDataBase(
    [property: Description("UUIDv7, generated by the client.")] Guid Id,
    [property: Description("UTC, ISO-8601 with milliseconds.")] DateTime CreatedAt,
    [property: Description("Time of the last change on the client that made it.")] DateTime ModifiedAt,
    [property: Description("Tombstone timestamp, null if not deleted.")] DateTime? DeletedAt,
    [property: Description("Server-assigned global change number. Ignored on push.")] long Version);
